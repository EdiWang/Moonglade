-- Run with all hosts stopped after the owner account schema upgrade.
BEGIN;

CREATE TABLE IF NOT EXISTS public.owner_oidc (
    id integer NOT NULL CONSTRAINT "PK_OwnerOidc" PRIMARY KEY,
    owner_id uuid NOT NULL CONSTRAINT "FK_OwnerOidc_OwnerAccount_OwnerId"
        REFERENCES public.owner_account (id) ON DELETE CASCADE,
    revision uuid NOT NULL,
    enabled boolean NOT NULL,
    display_name character varying(100) NOT NULL,
    authority character varying(500) NOT NULL,
    client_id character varying(500) NOT NULL,
    protected_secret text NOT NULL,
    issuer character varying(500),
    subject character varying(255),
    account_label character varying(255),
    session_revision uuid,
    CONSTRAINT "CK_OwnerOidc_Slot" CHECK (id = 1)
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_OwnerOidc_OwnerId" ON public.owner_oidc (owner_id);

CREATE TABLE IF NOT EXISTS public.data_protection_keys (
    id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_DataProtectionKeys" PRIMARY KEY,
    friendly_name text,
    xml text
);

COMMIT;
