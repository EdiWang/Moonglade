using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Moonglade.Data;
using Moonglade.Data.Entities;
using Moonglade.Data.PostgreSql;
using Moonglade.Data.SqlServer;

namespace Moonglade.Setup.Tests.Database;

public class CategoryIdentityModelTests
{
    [Theory]
    [InlineData("PostgreSql")]
    [InlineData("SqlServer")]
    public void ProviderModel_CategoryIdentityStartsAt100AndPostGuidIsUnchanged(string provider)
    {
        using BlogDbContext db = provider == "PostgreSql"
            ? new PostgreSqlBlogDbContext(new DbContextOptionsBuilder<PostgreSqlBlogDbContext>()
                .UseNpgsql("Host=localhost;Database=model_only").Options)
            : new SqlServerBlogDbContext(new DbContextOptionsBuilder<SqlServerBlogDbContext>()
                .UseSqlServer("Server=localhost;Database=model_only;Integrated Security=true").Options);
        var model = db.GetService<IDesignTimeModel>().Model;
        var category = model.FindEntityType(typeof(CategoryEntity))!;
        var id = category.FindProperty(nameof(CategoryEntity.Id))!;
        Assert.Equal(typeof(int), id.ClrType);
        Assert.Equal(ValueGenerated.OnAdd, id.ValueGenerated);
        Assert.False(id.IsNullable);
        Assert.Equal(typeof(int), model.FindEntityType(typeof(PostCategoryEntity))!
            .FindProperty(nameof(PostCategoryEntity.CategoryId))!.ClrType);
        Assert.Equal(typeof(Guid), model.FindEntityType(typeof(PostEntity))!
            .FindProperty(nameof(PostEntity.Id))!.ClrType);
        Assert.Equal(typeof(Guid), model.FindEntityType(typeof(PostCategoryEntity))!
            .FindProperty(nameof(PostCategoryEntity.PostId))!.ClrType);
        var ddl = db.Database.GenerateCreateScript();
        if (provider == "SqlServer")
        {
            Assert.Contains("IDENTITY(100, 1)", ddl);
            Assert.Equal(100L, id.FindAnnotation("SqlServer:IdentitySeed")!.Value);
            Assert.Equal(1, id.FindAnnotation("SqlServer:IdentityIncrement")!.Value);
        }
        else
        {
            Assert.Equal("IdentityByDefaultColumn", id.FindAnnotation("Npgsql:ValueGenerationStrategy")!.Value!.ToString());
            Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", ddl);
            Assert.Contains("START WITH 100", ddl);
        }
    }
}
